import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:960},reducedMotion:'no-preference'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:5173/');
await page.mouse.move(900,400);await page.mouse.wheel(0,400);
await page.locator('.scene-active[data-scene="hagiang"]').waitFor();
await page.waitForTimeout(1250);
await page.screenshot({path:'/tmp/rtg-motion-mountain.png'});
assert.equal(await page.evaluate(()=>scrollY),0);
await page.mouse.wheel(0,400);
await page.locator('.scene-active[data-scene="danang"]').waitFor();
await page.waitForTimeout(1250);
await page.screenshot({path:'/tmp/rtg-motion-coast.png'});
assert.equal(await page.evaluate(()=>scrollY),0);
await page.getByRole('link',{name:'Xem lịch trình Đà Nẵng',exact:true}).click();
await page.locator('.scene-active[data-scene="journey"]').waitFor();
assert.equal(await page.locator('.scene-active .segmented').getByRole('button',{name:'Đà Nẵng'}).getAttribute('aria-pressed'),'true');
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:'Cảnh 3: Đà Nẵng',exact:true}).click();
await page.waitForTimeout(1250);await page.screenshot({path:'/tmp/rtg-motion-mobile.png'});
await page.getByRole('button',{name:'Cảnh 8: Khảo sát',exact:true}).click();
await page.waitForTimeout(1250);
await page.mouse.move(180,400);await page.mouse.wheel(0,250);
assert.equal(await page.locator('.scene-active').getAttribute('data-scene'),'quiz');
assert.equal(await page.locator('.scene-active').evaluate(el=>el.scrollTop),0,'No inner scrolling');
assert.equal(await page.evaluate(()=>scrollY),0);
await page.emulateMedia({reducedMotion:'reduce'});
assert.equal(await page.locator('.scene-active').evaluate(el=>getComputedStyle(el).transform),'none');
await page.getByRole('radio',{name:/Lên núi/}).click();
await page.getByRole('button',{name:'Tiếp theo',exact:true}).click();
await page.getByRole('heading',{name:'Mức chi nào khiến bạn thoải mái?'}).waitFor();
assert.deepEqual(errors,[]);
console.log('PASS: real wheel changes fixed scenes without window scroll; cinematic frames desktop/mobile; scene links; all content paged without scroll; reduced motion and quiz interactions.');
await browser.close();
